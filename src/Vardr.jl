"""
    Vardr

A general-purpose framework for building digital twins on top of SciML.

A digital twin couples a model of the real system with a probabilistic belief about
the system's state, keeps that belief synchronized with incoming observations (data
assimilation), and answers forecast and what-if questions. The model can be an ODE
(any `ODEProblem`, including those generated by ModelingToolkit), a neural or hybrid
ODE, or an agent-based simulation.

See [`AbstractTwinModel`](@ref), [`ObservationModel`](@ref), [`Twin`](@ref).
"""
