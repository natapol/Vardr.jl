"""
    Vardr

A general-purpose framework for building digital twins on top of SciML.

A digital twin couples a mechanistic model (any `ODEProblem`, including those
generated by ModelingToolkit) with a probabilistic belief about the real system's
state, keeps that belief synchronized with incoming observations (data
assimilation), and answers forecast and what-if questions.

See [`TwinModel`](@ref), [`ObservationModel`](@ref), [`Twin`](@ref).
"""
